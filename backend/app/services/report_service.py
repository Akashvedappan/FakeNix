def _report_folder() -> str:
    return current_app.config.get('REPORT_FOLDER', 'storage/reports')


def _is_current_layout(filename: str | None) -> bool:
    return bool(filename) and filename.endswith(f'_v{REPORT_LAYOUT_VERSION}.pdf')


def get_report_path(report: Report) -> str | None:
    """
    Return the absolute path of the report PDF to serve, or None when it has to
    be (re)built first: the file is missing, or it is from an older layout and
    the detection it was built from still exists.
    """
    if not report or not report.report_path:
        return None
    full_path = os.path.join(_report_folder(), os.path.basename(report.report_path))
    if not os.path.exists(full_path):
        return None
    if _is_current_layout(report.report_path) or report.detection is None:
        return full_path
    return None


def _generate_pdf_for_report(report: Report, user=None) -> str:
    """
    Make sure the report has a current PDF on disk, building it under the
    report's existing ID if needed. Returns '' on success or an error message.
    Never creates detection or evidence records.
    """
    if get_report_path(report):
        return ''

    detection = report.detection
    if detection is None:
        return 'The detection this report was generated from no longer exists.'
    evidence = detection.evidence.order_by(Evidence.id).first()

    # A new file name per layout version: an existing PDF is never overwritten.
    filename = f'{report.report_uid.replace("-", "_")}_v{REPORT_LAYOUT_VERSION}.pdf'
    os.makedirs(_report_folder(), exist_ok=True)
    error = _generate_pdf(os.path.join(_report_folder(), filename), report, detection, evidence)
    if error:
        report.status = 'error'
        db.session.commit()
        return error

    report.report_path = filename
    report.status = 'ready'
    db.session.commit()
    logger.info(f'Report PDF written: {filename}')
    return ''


