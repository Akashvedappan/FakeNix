"""
FAKENIX 2.0 — PDF Report Generation Service using ReportLab

Generates forensic analysis reports. Reports are stored in backend/storage/reports/.

Rules this module holds to:
  - A report is only created for a detection that exists. A missing detection
    or report is an error for the caller, never a reason to make one up.
  - Everything printed comes from the stored detection / evidence records or is
    measured from the stored evidence file. Missing values are shown as missing.
  - Every table has explicit column widths that fit the page and every cell is
    a Paragraph, so long text wraps instead of being clipped.

DISCLAIMER: These reports are generated by FAKENIX AI software and are
intended for informational purposes only. They do not constitute official
government evidence or legal documentation.
"""
