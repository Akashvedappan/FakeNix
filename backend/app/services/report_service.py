# Bump when the PDF layout or wording changes. A stored PDF from an older layout
# is rebuilt on its next download into a new file; the old file is left in place.
REPORT_LAYOUT_VERSION = 2

DETECTION_NOT_FOUND = 'Detection not found.'
VERDICTS = {'real': 'REAL', 'authentic': 'REAL', 'deepfake': 'FAKE', 'fake': 'FAKE', 'suspicious': 'SUSPICIOUS'}
GROQ_SUFFIX = ' (Groq)'
# What a filename extension claims, in Pillow's format names.
EXTENSION_FORMATS = {'.jpg': 'JPEG', '.jpeg': 'JPEG', '.png': 'PNG', '.webp': 'WEBP'}


