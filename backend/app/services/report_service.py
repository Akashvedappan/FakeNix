def _utc(dt: datetime | None) -> str | None:
    """Format a datetime as UTC. Naive values are UTC already (that is how they are stored)."""
    if dt is None:
        return None
    if dt.tzinfo is not None:
        dt = dt.astimezone(timezone.utc)
    return dt.strftime('%Y-%m-%d %H:%M:%S')


def _load_json(text, expected):
    try:
        value = json.loads(text) if text else None
    except (TypeError, ValueError):
        value = None
    return value if isinstance(value, expected) else expected()


def _format_bytes(size: int) -> str:
    if size < 1024:
        return f'{size} B'
    if size < 1024 * 1024:
        return f'{size / 1024:.1f} KB'
    return f'{size / 1024 / 1024:.2f} MB'


def _stored_evidence_path(evidence: Evidence | None) -> str | None:
    """Absolute path of the stored evidence file, if it is on disk."""
    if not evidence or not evidence.file_path:
        return None
    path = os.path.join(current_app.config.get('UPLOAD_FOLDER', ''), os.path.basename(evidence.file_path))
    return path if os.path.isfile(path) else None


def check_evidence_integrity(evidence: Evidence | None) -> dict:
    """
    Re-hash the stored evidence file and compare it with the SHA-256 recorded at
    upload. Read-only: the evidence record is not modified.

    'state' is one of: match, mismatch, unavailable, no_hash, no_evidence.
    """
    if evidence is None:
        return {'state': 'no_evidence', 'short': 'NO EVIDENCE FILE',
                'label': 'NO EVIDENCE FILE — no evidence record exists for this detection, '
                         'so there is no file hash to verify.'}

    result = {'sha256': evidence.sha256_hash or None, 'md5': evidence.md5_hash or None,
              'recorded_at': _utc(evidence.created_at)}
    if not evidence.sha256_hash:
        return {**result, 'state': 'no_hash', 'short': 'NOT VERIFIED',
                'label': 'NOT VERIFIED — no SHA-256 hash was recorded for this evidence.'}

    path = _stored_evidence_path(evidence)
    try:
        actual = calculate_sha256(path) if path else None
    except Exception:
        actual = None
    if not actual:
        return {**result, 'state': 'unavailable', 'short': 'NOT VERIFIED',
                'label': 'NOT VERIFIED — the stored evidence file is not available, so the recorded hash '
                         'could not be re-checked.'}

    checked_at = _utc(datetime.now(timezone.utc))
    if actual.lower() == evidence.sha256_hash.lower():
        return {**result, 'state': 'match', 'short': 'HASH MATCH',
                'label': f'MATCH — the stored evidence file was re-hashed on {checked_at} UTC and its SHA-256 '
                         'equals the recorded value.'}
    return {**result, 'state': 'mismatch', 'short': 'HASH MISMATCH', 'actual_sha256': actual,
            'label': f'MISMATCH — the stored evidence file was re-hashed on {checked_at} UTC and its SHA-256 '
                     'differs from the recorded value. The stored file has been changed or replaced since '
                     'the hash was recorded.'}


def _measure_stored_file(path: str | None, file_type: str) -> dict:
    """Size, and for images the real format, read from the stored evidence file itself."""
    measured = {}
    if not path:
        return measured
    try:
        measured['size_bytes'] = os.path.getsize(path)
        if file_type == 'image':
            from PIL import Image
            with Image.open(path) as img:
                measured['format'] = 'JPEG' if img.format == 'MPO' else img.format
                measured['mime'] = Image.MIME.get(img.format)
                measured['dimensions'] = f'{img.width} × {img.height} px'
    except Exception as e:
        logger.warning(f'Could not measure stored evidence file: {e}')
    return measured


def build_report_context(report: Report, detection: Detection, evidence: Evidence | None) -> dict:
    """Everything the PDF prints, taken from the stored report, detection and evidence."""
    meta = _load_json(detection.metadata_json, dict)
    is_demo = bool(detection.is_demo)
    file_type = detection.file_type or ''

    # Detection.confidence and Detection.deepfake_probability hold the same value:
    # the 0-100 likelihood that the media is FAKE. real_probability is 100 minus it.
    deepfake = detection.deepfake_probability if detection.deepfake_probability is not None else detection.confidence
    authentic = detection.real_probability
    if authentic is None and deepfake is not None:
        authentic = round(100 - deepfake, 1)

    stored_model = detection.model_name or None
    if is_demo:
        analysis_type = 'Simulated demo result — no model inference was run'
        provider = 'None (no inference provider was called)'
        model = f'None (stored label: "{stored_model}")' if stored_model else 'None'
        source = None
    else:
        analysis_type = 'AI model inference (vision language model)'
        from_groq = bool(stored_model) and stored_model.endswith(GROQ_SUFFIX)
        provider = 'Groq Cloud' if from_groq else None
        model = stored_model[:-len(GROQ_SUFFIX)] if from_groq else stored_model
        source = ' via '.join(part for part in (model, provider) if part) or 'the analysing model'

    # File facts: measured from the stored file when it exists, else as recorded at upload.
    stored_path = _stored_evidence_path(evidence)
    measured = _measure_stored_file(stored_path, file_type)
    extension = os.path.splitext(detection.file_name or '')[1].lower() or None
    file_format = measured.get('format') or meta.get('format')
    size_bytes = measured.get('size_bytes', meta.get('fileSizeBytes'))
    if size_bytes is not None:
        file_size = f'{_format_bytes(size_bytes)} ({size_bytes:,} bytes)'
    else:
        file_size = detection.file_size if re.search(r'\d\s*(B|KB|MB|GB)$', detection.file_size or '') else None
    width, height = meta.get('width'), meta.get('height')
    dimensions = measured.get('dimensions') or (f'{width} × {height} px' if width and height else detection.resolution)

    inconsistencies = []
    claimed = EXTENSION_FORMATS.get(extension or '')
    if file_type == 'image' and claimed and file_format and claimed != file_format:
        inconsistencies.append(f'Filename extension "{extension}" indicates {claimed}, '
                               f'but the file content is {file_format}.')

    indicators = []
    for item in _load_json(detection.indicators_json, list):
        if not isinstance(item, dict) or not str(item.get('name') or '').strip():
            continue
        score = item.get('score')
        if isinstance(score, bool) or not isinstance(score, (int, float)):
            score = None
        elif score > 1:  # stored on a 0-100 scale
            score = score / 100
        indicators.append({'name': item['name'], 'score': score,
                           'severity': item.get('severity'), 'evidence': item.get('evidence')})

    thresholds = current_app.config.get('RISK_THRESHOLDS', {})
    low_max = thresholds.get('low', (0.0, 30.0))[1]
    medium_max = thresholds.get('suspicious', (30.0, 70.0))[1]
    verdict = VERDICTS.get((detection.result or '').lower(), 'UNDETERMINED')
    notes = []
    if deepfake is None:
        notes.append('No deepfake probability is stored for this detection.')
    elif (verdict == 'REAL' and deepfake >= low_max) or (verdict == 'FAKE' and deepfake < low_max):
        notes.append(f'The stored verdict ({verdict}) is not consistent with the stored deepfake probability '
                     f'({deepfake:.1f}%). Treat this result as inconclusive.')

    return {
        'report_id': report.report_uid,
        'generated_at': _utc(report.created_at),
        'generated_by': report.generated_by or 'FAKENIX System',
        'evidence_id': evidence.evidence_uid if evidence else None,
        'detection_id': detection.detection_uid,
        'is_demo': is_demo,
        'verdict': verdict,
        'risk_level': detection.risk_level,
        'deepfake_probability': deepfake,
        'authentic_probability': authentic,
        'risk_bands': (f'below {low_max:.0f}% low, {low_max:.0f}–{medium_max:.0f}% medium, '
                       f'{medium_max:.0f}% and above high, 95% and above critical'),
        'notes': notes,
        'file_name': None if file_type == 'url' else detection.file_name,
        'source_url': (detection.source_url or detection.file_name) if file_type == 'url' else None,
        'file_type': file_type.upper() or None,
        'file_size': file_size,
        'dimensions': dimensions,
        'duration': (detection.duration or meta.get('duration') or 'Not determined') if file_type == 'video' else None,
        'uploaded_at': _utc(detection.created_at),
        'measured_from_file': bool(measured),
        'integrity': check_evidence_integrity(evidence),
        'metadata': {
            'extension': extension if file_type != 'url' else None,
            'format': file_format,
            # Only a MIME type derived from the file content; never the filename's guess.
            'mime': measured.get('mime'),
            'mode': meta.get('mode'),
            'fps': f'{meta["fps"]} fps' if meta.get('fps') else None,
            'codec': meta.get('codec'),
            'exif': {True: 'None present', False: 'Present'}.get(meta.get('exifStripped')),
            'software': meta.get('softwareTag') if meta.get('softwareTag') not in ('Unknown', '') else None,
            'created': meta.get('created'),
            'inconsistencies': inconsistencies,
        },
        'indicators': indicators,
        'frames': [f for f in _load_json(detection.frames_json, list) if isinstance(f, dict)] if file_type == 'video' else [],
        'analysis_type': analysis_type,
        'model': model,
        'provider': provider,
        'source': source,
        'observations': None if is_demo else (meta.get('aiExplanation') or None),
    }


