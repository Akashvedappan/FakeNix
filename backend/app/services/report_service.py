def generate_report(detection_uid: str, user=None) -> tuple[Report | None, str]:
    """
    Return the report for a detection, creating it (and its PDF) on first request.

    Args:
        detection_uid: Detection UID string or ID
        user: User object (or None for demo)

    Returns:
        (report, error_message)
    """
    ref = str(detection_uid)
    detection = db.session.query(Detection).filter(Detection.detection_uid == ref).first()
    if not detection and ref.isdigit():
        detection = db.session.query(Detection).filter(Detection.id == int(ref)).first()

    user_id = getattr(user, 'id', None)
    if detection and user_id and detection.user_id not in (None, user_id):
        detection = None  # someone else's detection
    if not detection:
        return None, DETECTION_NOT_FOUND
    if detection.status != 'complete' or not detection.result:
        return None, 'This detection has no completed analysis result to report on.'
    detection_id = detection.id

    report = _report_for_detection(detection_id)
    if not report:
        report = _create_report_record(detection_id, user)
        if not report:
            return None, 'Could not allocate a unique report ID. Please try again.'

    error = _generate_pdf_for_report(report, user)
    if error:
        return None, error
    return report, ''


def _report_for_detection(detection_id: int) -> Report | None:
    return db.session.query(Report).filter(Report.detection_id == detection_id).order_by(Report.id).first()


def _create_report_record(detection_id: int, user) -> Report | None:
    """
    Insert the report row, which reserves its ID, before any PDF is written.
    report_uid is UNIQUE: if a concurrent request took the proposed ID, the insert
    fails, and we either adopt the report that request created or try the next ID.
    """
    for _ in range(5):
        report = Report(
            report_uid=_next_report_uid(),
            user_id=getattr(user, 'id', None),
            detection_id=detection_id,
            report_type='Forensic Analysis',
            status='generating',
            generated_by=getattr(user, 'full_name', None) or 'FAKENIX System',
        )
        db.session.add(report)
        try:
            db.session.commit()
            logger.info(f'Report record created: {report.report_uid}')
            return report
        except IntegrityError:
            db.session.rollback()
            existing = _report_for_detection(detection_id)
            if existing:
                return existing
    return None


def _next_report_uid() -> str:
    """
    Propose the next FX-RPT-<year>-<n> ID. Numbers are never reissued: besides the
    IDs in the table, PDFs already in the report folder count as used, so an ID
    whose row was deleted cannot be given to another detection.
    """
    year = datetime.now(timezone.utc).year
    highest = 0
    uid_pattern = re.compile(rf'^FX-RPT-{year}-(\d+)$')
    for (uid,) in db.session.query(Report.report_uid).filter(Report.report_uid.like(f'FX-RPT-{year}-%')):
        match = uid_pattern.match(uid or '')
        if match:
            highest = max(highest, int(match.group(1)))
    file_pattern = re.compile(rf'^FX_RPT_{year}_(\d+)(?:_v\d+)?\.pdf$')
    try:
        for name in os.listdir(_report_folder()):
            match = file_pattern.match(name)
            if match:
                highest = max(highest, int(match.group(1)))
    except OSError:
        pass
    return f'FX-RPT-{year}-{highest + 1:03d}'


def get_all_reports(user_id: int = None) -> list:
    """Get all reports for a user (plus reports without an owner), or all reports."""
    query = db.session.query(Report)
    if user_id:
        query = query.filter((Report.user_id == user_id) | (Report.user_id == None))  # noqa: E711
    return [r.to_dict() for r in query.order_by(Report.created_at.desc()).all()]


def get_report_by_uid(report_uid: str, user_id: int = None) -> Report | None:
    """Get a single report by UID, if it is visible to the user."""
    uid = str(report_uid)
    report = db.session.query(Report).filter(Report.report_uid == uid).first()
    if not report and uid.startswith('rpt_') and uid[4:].isdigit():
        report = db.session.query(Report).filter(Report.id == int(uid[4:])).first()
    if report and user_id and report.user_id not in (None, user_id):
        return None
    return report


